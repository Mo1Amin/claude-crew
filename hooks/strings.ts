let language: CrewLanguage = 'en'

export function setLanguage(next: CrewLanguage): void {
  language = next
}

export const isRtl = (): boolean => language === 'ar'
export const lang = (): CrewLanguage => language
export const verbs = (): Record<string, string> => (language === 'ar' ? VERBS_AR : VERBS_EN)

export function t(key: Key, values: Record<string, string | number> = {}): string {
  const text = (language === 'ar' ? AR : EN)[key]
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => String(values[name] ?? whole))
}
